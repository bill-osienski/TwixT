def _committed_set(monkeypatch, tmp_path):
    """A stand-in for a generated, committed held-out set: two existing files, `_committed` answering yes."""
    for name in ("record.json", "heldout.json"):
        (tmp_path / name).write_text("{}")
    monkeypatch.setattr(TR, "HELDOUT_RECORD", str(tmp_path / "record.json"))
    monkeypatch.setattr(TR, "HELDOUT_JSON", str(tmp_path / "heldout.json"))
    monkeypatch.setattr(TR, "_committed", lambda rel: True)



def test_THE_NEW_SET_IS_SCORED_ONLY_FOR_THE_BASELINE_AND_THE_FINAL_CHECK(rig, tmp_path, monkeypatch):
    real_read = TR.read_heldout
    box = {}

    def read(spec, a, b):
        records, summary = real_read(spec, a, b)
        box["held"] = {id(r) for r in records}
        return records, summary

    seen, real_forward, real_train = [], D.forward, D.train_student

    def forward(network, records, chunk=64):
        if any(id(r) in box["held"] for r in records):
            seen.append("held_out")
        return real_forward(network, records, chunk)

    def train(student, teacher, records, recipe, **kw):
        assert not any(id(r) in box["held"] for r in records)
        seen.append("train")
        return real_train(student, teacher, records, recipe, **kw)

    monkeypatch.setattr(TR, "read_heldout", read)
    monkeypatch.setattr(D, "forward", forward)
    monkeypatch.setattr(D, "train_student", train)
    code, rec = REAL_CONCLUDE(rig["spec"], _seams(rig), tmp_path / "ev", tmp_path / "s.safetensors")
    assert rec["status"] == "COMPLETED", rec.get("void")
    assert seen == ["held_out", "held_out", "train", "held_out"]        # baseline (values + metrics); final



def test_REAL_THE_TRAINING_ONLY_READER_on_the_real_corpus_opens_no_original_held_out_file():
    raw = (TR.ROOT / TR.CORPUS_JSON).read_bytes()
    records, summary = TR.read_training(TR.FROZEN, raw)
    corpus = json.loads(raw)
    held = corpus["held_out_games"]
    assert len(records) == 6403 and summary["training_ids_sha256"] == TR.FROZEN["training_ids_sha256"]
    assert summary["original_held_out"] == {"games": held, "files_opened": 0, "records_read": 0} and len(held) == 12
    held_paths = {f"{ph['dir']}/{C._game_path(g)}" for ph in corpus["phases"] for g in ph["games"] if g in held}
    assert len(held_paths) == 12 and not held_paths & set(summary["files_opened"])
    assert sum(p.split("/", 1)[1].startswith("games/") for p in summary["files_opened"]) == 108


